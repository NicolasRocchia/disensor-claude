"""Regenerates the texts this plugin takes from the disensor CLI it pins.

The runbook in skills/round/SKILL.md and the filling guide in its references/
come from the pinned disensor, never from a hand copy: `disensor init --show`
prints the runbook the CLI writes as a repository skill, and `disensor guide`
prints that runbook followed by the filling guide. The setup skill takes the
pinned version from here. tests/test_contrato.py regenerates everything and
compares it with what is committed, so a drift between the plugin and the CLI
fails before it ships instead of after.

Run it from the plugin root with the pinned disensor on PATH:

    python tools/generar.py
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

PIN = "0.12.1"

ROOT = Path(__file__).resolve().parent.parent
RUNBOOK_HEADER = "# .claude/skills/disensor/SKILL.md"
GUIDE_HEADER = "# How to fill a residue declaration"
LF = chr(10)
CRLF = chr(13) + LF

ROUND_FRONTMATTER = """---
name: round
description: Run the adversarial review round with the disensor CLI and declare its residue, when the user invokes it to close a plan, a diff or an architecture decision, or to fill the declaration a round produced.
disable-model-invocation: true
---

This skill drives the `disensor` CLI, installed and set up with
`/disensor:setup`. It runs only when the user invokes it: the round sends the
material under review to the reviewer the owner registered and consented to,
and that is the owner's call every time.

Four rules that sit above the runbook below:

- Start with `disensor --version`. This plugin was written for {pin}; if the
  shell resolves another version, say so and stop.
- If the tree is not clean, say so and let the user commit. Do not commit,
  stash or discard anything for them.
- A candidate reviewer outside the catalogue is an executable that will later
  receive the material under review. Do not run it, not even with `--help`,
  before the owner approves registering it.
- When more than one round ran, the declaration lists the findings of every
  round, not only the last report. A clean last report does not erase what the
  earlier ones found.

"""

# Lo unico que cambia respecto del texto que imprime el CLI, y por que. Cada
# reemplazo se busca ignorando como el CLI corto las lineas, y tiene que
# aparecer exactamente una vez: si el texto del CLI cambia, esto falla a
# proposito y hay que mirar que paso. Los tres ultimos corrigen el runbook de
# la 0.12.1 (reportados a disensor); cuando el CLI los arregle, se borran.
ROUND_REWRITES = [
    (
        "`disensor guide` explains every field.",
        "The filling guide in `references/guide.md`, next to this file, explains every field.",
    ),
    (
        "pass `--gate plan --material <file>`:",
        "pass `--gate plan` or `--gate architecture` with `--material <file>`:",
    ),
    (
        "disensor new --gate diff --level <A|B|C> --round <result>",
        "disensor new --gate <the gate of the round> --level <A|B|C> --round <result>",
    ),
    (
        "and `disensor gate --no-comment` green. The declaration goes in its own commit, "
        "never mixed with code.",
        "and commit the declaration in its own commit, never mixed with code. Then "
        "`disensor gate --no-comment --base <target branch> --head HEAD` has to be green: "
        "the gate reads the declarations that are committed in that range.",
    ),
]

GUIDE_NOTE = (
    "<!-- Generated by tools/generar.py from `disensor guide` of disensor {pin}. "
    "Do not edit: regenerate. -->" + LF + LF
    + "The procedure is the runbook in SKILL.md. The section \"The round, and then the "
    + "declaration\" below describes the manual path for an agent without the runner: it "
    + "does not apply here. Never hand material to a reviewer by hand, and declare with "
    + "`disensor new --round <result>`." + LF + LF
)


def cli(*args: str) -> str:
    out = subprocess.run(["disensor", *args], capture_output=True, check=True)
    return out.stdout.decode("utf-8").replace(CRLF, LF)


def installed_version() -> str:
    return cli("--version").strip().split()[-1]


def rewrite(text: str, old: str, new: str) -> str:
    """Replace `old` wherever the CLI wrapped it, exactly once."""
    pattern = r"\s+".join(re.escape(word) for word in old.split())
    text, n = re.subn(pattern, new, text)
    assert n == 1, f"rewrite target found {n} times: {old!r}"
    return text


def round_skill(pin: str) -> str:
    shown = cli("init", "--show")
    assert shown.count(RUNBOOK_HEADER) == 1, "disensor init --show changed shape"
    body = shown.split(RUNBOOK_HEADER, 1)[1]
    # El CLI imprime la skill con su frontmatter; la del plugin es otra.
    assert body.count("---") >= 2, "no frontmatter in the printed skill"
    body = body.split("---", 2)[2].lstrip(LF)
    for old, new in ROUND_REWRITES:
        body = rewrite(body, old, new)
    return ROUND_FRONTMATTER.format(pin=pin) + body.rstrip(LF) + LF


def guide_reference(pin: str) -> str:
    # Solo la guia de llenado: el runbook que la precede ya es SKILL.md, y
    # traerlo de nuevo volveria a decir que `disensor guide` explica los campos.
    shown = cli("guide")
    assert shown.count(GUIDE_HEADER) == 1, "disensor guide changed shape"
    guide = shown[shown.index(GUIDE_HEADER):]
    return GUIDE_NOTE.format(pin=pin) + guide.rstrip(LF) + LF


def setup_skill(pin: str) -> str:
    template = (ROOT / "tools" / "plantillas" / "setup.md").read_bytes().decode("utf-8")
    assert template.count("{{PIN}}") >= 1
    return template.replace("{{PIN}}", pin)


def generate(pin: str) -> dict[Path, str]:
    return {
        ROOT / "skills" / "round" / "SKILL.md": round_skill(pin),
        ROOT / "skills" / "round" / "references" / "guide.md": guide_reference(pin),
        ROOT / "skills" / "setup" / "SKILL.md": setup_skill(pin),
    }


def main() -> int:
    actual = installed_version()
    if actual != PIN:
        print(f"the plugin pins disensor {PIN} but {actual} is installed; install the pin first")
        return 1
    for path, text in generate(PIN).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text.encode("utf-8"))
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
